CREATE TABLE IF NOT EXISTS detection_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detection_id BIGINT NOT NULL REFERENCES step_detections(id),
    template_id BIGINT REFERENCES method_work_steps(id),
    name_snapshot TEXT NOT NULL CHECK (length(trim(name_snapshot)) > 0),
    coefficient_snapshot DOUBLE PRECISION NOT NULL CHECK (coefficient_snapshot >= 0 AND coefficient_snapshot < 'Infinity'::float8),
    sort_order INTEGER NOT NULL CHECK (sort_order >= 0),
    UNIQUE (detection_id, id),
    UNIQUE (detection_id, sort_order)
);

CREATE TABLE IF NOT EXISTS detection_quantity_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detection_id BIGINT NOT NULL REFERENCES step_detections(id),
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    UNIQUE (detection_id, id)
);

CREATE TABLE IF NOT EXISTS step_work_entries (
    work_record_id BIGINT PRIMARY KEY REFERENCES work_records(id),
    detection_id BIGINT NOT NULL REFERENCES step_detections(id),
    group_id BIGINT NOT NULL,
    step_id BIGINT NOT NULL,
    rework BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (detection_id, work_record_id),
    FOREIGN KEY (detection_id, group_id) REFERENCES detection_quantity_groups(detection_id, id),
    FOREIGN KEY (detection_id, step_id) REFERENCES detection_steps(detection_id, id)
);

-- Completed detections and separately billed rework use distinct charge records.
CREATE TABLE IF NOT EXISTS step_detection_charges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detection_id BIGINT NOT NULL REFERENCES step_detections(id),
    rework_record_id BIGINT,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price DOUBLE PRECISION NOT NULL CHECK (unit_price >= 0 AND unit_price < 'Infinity'::float8),
    multiplier DOUBLE PRECISION NOT NULL CHECK (multiplier >= 0 AND multiplier < 'Infinity'::float8),
    charged_at TIMESTAMPTZ NOT NULL,
    voided_at TIMESTAMPTZ,
    void_reason TEXT,
    FOREIGN KEY (detection_id, rework_record_id) REFERENCES step_work_entries(detection_id, work_record_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_step_detection_active_normal_charge
    ON step_detection_charges(detection_id)
    WHERE rework_record_id IS NULL AND voided_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_step_detection_active_rework_charge
    ON step_detection_charges(rework_record_id)
    WHERE rework_record_id IS NOT NULL AND voided_at IS NULL;

CREATE OR REPLACE FUNCTION step_source_completed_quantity(source_kind TEXT, source_id BIGINT)
RETURNS BIGINT LANGUAGE SQL STABLE AS $$
    SELECT COALESCE((SELECT SUM(per_group.completed) FROM (
        SELECT g.id, MIN(COALESCE((SELECT SUM(w.quantity)
            FROM step_work_entries e JOIN work_records w ON w.id=e.work_record_id
            WHERE e.group_id=g.id AND e.step_id=s.id AND NOT e.rework AND w.deleted_at IS NULL),0)) AS completed
        FROM detection_quantity_groups g CROSS JOIN detection_steps s
        WHERE g.detection_id=d.id AND s.detection_id=d.id GROUP BY g.id
    ) per_group),0)::BIGINT FROM step_detections d
    WHERE d.source_type=source_kind AND d.source_record_id=source_id
$$;
