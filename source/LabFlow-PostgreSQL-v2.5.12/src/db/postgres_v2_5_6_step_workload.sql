-- Existing submissions retain their original accounting; only newly entered submissions use the new pending-step rule.
ALTER TABLE rd_work_records ADD COLUMN IF NOT EXISTS step_accounting_new BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE IF NOT EXISTS method_step_settings (
    method_id BIGINT PRIMARY KEY REFERENCES methods(id),
    ordered BOOLEAN NOT NULL DEFAULT FALSE,
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0)
);

CREATE TABLE IF NOT EXISTS method_work_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method_id BIGINT NOT NULL REFERENCES methods(id),
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    coefficient DOUBLE PRECISION NOT NULL CHECK (coefficient >= 0 AND coefficient < 'Infinity'::float8),
    sort_order INTEGER NOT NULL CHECK (sort_order >= 0),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (method_id, id)
);

CREATE TABLE IF NOT EXISTS step_detections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type TEXT CHECK (source_type IN ('rd_sample', 'sample_info_sample')),
    source_record_id BIGINT,
    method_id BIGINT NOT NULL REFERENCES methods(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    ordered BOOLEAN NOT NULL DEFAULT FALSE,
    unit_price DOUBLE PRECISION NOT NULL CHECK (unit_price >= 0 AND unit_price < 'Infinity'::float8),
    multiplier DOUBLE PRECISION NOT NULL CHECK (multiplier >= 0 AND multiplier < 'Infinity'::float8),
    created_by_user_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((source_type IS NULL) = (source_record_id IS NULL)),
    CHECK (source_record_id IS NULL OR source_record_id > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_step_detections_source
    ON step_detections(source_type, source_record_id)
    WHERE source_type IS NOT NULL;

