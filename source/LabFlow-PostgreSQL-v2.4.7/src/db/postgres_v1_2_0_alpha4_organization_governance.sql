UPDATE sample_info_records s
SET execution_group_id = s.group_id,
    execution_group_name_snapshot = COALESCE(NULLIF(s.lab_name, ''), ''),
    execution_division_id = COALESCE(
        s.division_id,
        (SELECT g.division_id FROM project_groups g WHERE g.id = s.group_id)
    ),
    execution_division_name_snapshot = COALESCE(
        (SELECT d.name
         FROM divisions d
         WHERE d.id = COALESCE(
             s.division_id,
             (SELECT g.division_id FROM project_groups g WHERE g.id = s.group_id)
         )),
        ''
    ),
    submitted_division_id = COALESCE(
        s.division_id,
        (SELECT g.division_id FROM project_groups g WHERE g.id = s.group_id)
    ),
    submitted_division_name_snapshot = COALESCE(
        (SELECT d.name
         FROM divisions d
         WHERE d.id = COALESCE(
             s.division_id,
             (SELECT g.division_id FROM project_groups g WHERE g.id = s.group_id)
         )),
        ''
    ),
    business_user_id = s.created_by_user_id,
    business_username_snapshot = COALESCE(NULLIF(s.user_name, ''), s.created_by_username_snapshot, ''),
    ownership_status = CASE
        WHEN COALESCE(
            s.division_id,
            (SELECT g.division_id FROM project_groups g WHERE g.id = s.group_id)
        ) IS NULL THEN 'pending_confirmation'
        ELSE 'confirmed'
    END
WHERE s.group_id IS NOT NULL
  AND (s.execution_division_id IS NULL OR s.execution_group_id IS NULL);

UPDATE sample_info_records s
SET ownership_status = 'pending_confirmation'
WHERE s.execution_division_id IS NULL;

UPDATE rd_work_records r
SET submitted_division_id = COALESCE(r.submitted_division_id, r.project_division_id),
    submitted_division_name_snapshot = COALESCE(
        NULLIF(r.submitted_division_name_snapshot, ''),
        r.project_division_name_snapshot,
        ''
    ),
    ownership_status = CASE
        WHEN r.execution_division_id IS NULL THEN 'pending_confirmation'
        ELSE r.ownership_status
    END;

UPDATE work_records SET ownership_status = 'pending_confirmation'
WHERE execution_division_id IS NULL;

